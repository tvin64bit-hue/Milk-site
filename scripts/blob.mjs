// Строит гладкий замкнутый контур блоба.
//
// Точки задаются парами [радиус, вес]: радиус — насколько далеко точка отходит
// от центра, вес — какую часть окружности занимает сектор до следующей точки.
// Неравные веса дают доли разной ширины: без них силуэт получается либо
// мятым кругом, либо правильной звездой, а нужна мягкая клякса.
//
// Между точками — кубические кривые Безье с касательными по Catmull-Rom,
// поэтому стыков не видно.
export function konturBloba(tochkiVhod, { povorot = 0, tochnost = 4 } = {}) {
  const n = tochkiVhod.length;
  const summaVesov = tochkiVhod.reduce((s, [, v]) => s + v, 0);

  let ugol = povorot;
  const tochki = tochkiVhod.map(([r, ves]) => {
    const t = [0.5 + Math.cos(ugol) * r, 0.5 + Math.sin(ugol) * r * 0.94];
    ugol += (ves / summaVesov) * Math.PI * 2;
    return t;
  });

  const ok = (i) => tochki[(i + n) % n];
  const f = (v) => Number(v.toFixed(tochnost));

  let d = `M${f(ok(0)[0])},${f(ok(0)[1])}`;
  for (let i = 0; i < n; i++) {
    const [p0, p1, p2, p3] = [ok(i - 1), ok(i), ok(i + 1), ok(i + 2)];
    // Коэффициент 1/6 даёт кривую, проходящую точно через заданные точки.
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += `C${f(c1[0])},${f(c1[1])} ${f(c2[0])},${f(c2[1])} ${f(p2[0])},${f(p2[1])}`;
  }
  return `${d}Z`;
}

