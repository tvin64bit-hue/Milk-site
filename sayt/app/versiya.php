<?php
// Проверка версии PHP. Подключается первой, до всего остального.
//
// Сайт написан под PHP 8.2. На версии старше сообщения об ошибке
// бесполезны: файлы с новым синтаксисом не читаются целиком, и посетитель
// видел вежливую заглушку «Что-то пошло не так», из которой невозможно
// догадаться, что дело в настройке хостинга. Так и вышло: хостинг отдавал
// PHP 7.1, а сайт молчал о причине.
//
// Файл намеренно написан на старом синтаксисе — без объявлений типов и
// стрелочных функций. Он должен выполниться даже там, где не выполняется
// ничего другого, иначе объяснять будет некому.

if (PHP_VERSION_ID < 80200) {
    $nuzhna = '8.2';
    $est = PHP_VERSION;
    http_response_code(500);
    header('Content-Type: text/html; charset=UTF-8');
    echo '<!doctype html><html lang="ru"><head><meta charset="utf-8">'
        . '<meta name="viewport" content="width=device-width, initial-scale=1">'
        . '<title>Нужна другая версия PHP</title></head>'
        . '<body style="font:16px/1.6 system-ui,sans-serif;margin:0;padding:2rem 1rem;background:#F8EEE4;color:#3D2B1C">'
        . '<main style="max-width:34rem;margin:0 auto">'
        . '<h1 style="font-size:1.4rem">Сайту нужна другая версия PHP</h1>'
        . '<p>Сейчас на сервере <b>PHP ' . htmlspecialchars($est, ENT_QUOTES) . '</b>, '
        . 'а сайт написан под <b>PHP ' . $nuzhna . '</b> или новее.</p>'
        . '<p>Это настройка хостинга, а не поломка сайта: версия переключается '
        . 'в панели управления — раздел с настройками сайта или домена. '
        . 'После переключения страницу достаточно обновить.</p>'
        . '<p style="color:#78644E">Пока версия не переключена, заказ можно сделать '
        . 'по телефону <a href="tel:+79613625943" style="color:#C85111">+7 961 362-59-43</a>.</p>'
        . '</main></body></html>';
    exit;
}
